-- Scrum of Azeroth by DinX: translations. Code uses English strings as keys: L["Text"].
-- Language: the setting ("auto", "enUS", "nlNL"); "auto" follows CasterKit's
-- language when CasterKit is loaded, otherwise the game client (GetLocale).
local _, ns = ...
local SoA = ns.SoA

local NL = {}
SoA.translations = { nlNL = NL }

function SoA:Language()
	local pref = self.db and self.db.language or "auto"
	if pref == "enUS" or pref == "nlNL" then return pref end
	local CK = _G.CasterKit
	if type(CK) == "table" and type(CK.db) == "table" and CK.db.language then
		return CK.db.language == "nlNL" and "nlNL" or "enUS"
	end
	return (GetLocale and GetLocale() == "nlNL") and "nlNL" or "enUS"
end

SoA.L = setmetatable({}, {
	__index = function(_, key)
		local lang = SoA:Language()
		if key == "decimal" then return lang == "nlNL" and "," or "." end
		if key == "thousands" then return lang == "nlNL" and "." or "," end
		local t = SoA.translations[lang]
		return t and t[key] or key
	end,
})
ns.L = SoA.L

